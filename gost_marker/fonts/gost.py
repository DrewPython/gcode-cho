@dataclass(frozen=True)
class StrokeFont:
    """Одноштриховой шрифт."""

    key: str
    name: str
    glyphs: dict[str, Glyph] = field(default_factory=dict)
    x_scale: float = 1.0
    cap_height: float = 1.0
    x_height: float = 0.70
    ascent: float = 1.0
    descent: float = -0.25
    default_letter_spacing: float = 0.143
    default_line_spacing: float = 1.57
    default_word_spacing: float = 0.43
    line_width: float = 1.0 / 14.0

    def glyph(self, char: str) -> Glyph | None:
        return self.glyphs.get(char)

    def get(self, char: str) -> Glyph:
        return self.glyphs[char]

    def __contains__(self, char: str) -> bool:
        return char in self.glyphs


def _build(key: str) -> StrokeFont:
    cyr_u = _cyrillic_upper()
    cyr_l = _cyrillic_lower()
    latin_u = _latin_upper(cyr_u)
    latin_l = _latin_lower(cyr_l)
    digits = _digits()
    symbols = _symbols(cyr_u, cyr_l)

    all_glyphs: dict[str, Glyph] = {}
    all_glyphs.update(cyr_u)
    all_glyphs.update(cyr_l)
    all_glyphs.update(latin_u)
    all_glyphs.update(latin_l)
    all_glyphs.update(digits)
    all_glyphs.update(symbols)

    generated = _GENERATED_DATA.get(key)
    if generated:
        for char, (width, strokes) in generated["glyphs"].items():
            all_glyphs[char] = Glyph(
                width=float(width),
                strokes=tuple(
                    tuple((float(x), float(y)) for x, y in stroke)
                    for stroke in strokes
                ),
            )
        if key == "B":
            # Ручные символы-исключения были нарисованы в системе типа A
            # и раньше масштабировались через x_scale. Теперь координаты
            # сгенерированы сразу в системе типа B, поэтому масштабируем
            # только оставшиеся ручные глифы.
            sx = 1.16
            for char, glyph in list(all_glyphs.items()):
                if char in generated["glyphs"]:
                    continue
                all_glyphs[char] = Glyph(
                    width=glyph.width * sx,
                    strokes=tuple(
                        tuple((x * sx, y) for x, y in stroke)
                        for stroke in glyph.strokes
                    ),
                )
        return StrokeFont(
            key=key,
            name="ГОСТ тип А" if key == "A" else "ГОСТ тип Б",
            glyphs=all_glyphs,
            x_scale=1.0,
            cap_height=1.0,
            x_height=float(generated.get("x_height", 0.70)),
            ascent=float(generated.get("ascent", 1.0)),
            descent=float(generated.get("descent", -0.25)),
            default_letter_spacing=float(generated.get("letter_spacing", 0.0)),
            default_line_spacing=float(generated.get("line_spacing", 1.57)),
            default_word_spacing=float(generated.get("word_spacing", 0.43)),
            line_width=float(generated.get("line_width", 1.0 / 14.0)),
        )

    if key == "A":
        return StrokeFont(
            key="A",
            name="ГОСТ тип А",
            glyphs=all_glyphs,
            x_scale=1.0,
            default_letter_spacing=0.143,
            default_line_spacing=1.57,
            default_word_spacing=0.43,
            line_width=1.0 / 14.0,
        )
    if key == "B":
        return StrokeFont(
            key="B",
            name="ГОСТ тип Б",
            glyphs=all_glyphs,
            x_scale=1.16,
            default_letter_spacing=0.20,
            default_line_spacing=1.70,
            default_word_spacing=0.60,
            line_width=1.0 / 10.0,
        )
    raise ValueError(f"Неизвестный шрифт: {key}")


FONT_A = _build("A")
FONT_B = _build("B")
FONTS: dict[str, StrokeFont] = {"A": FONT_A, "B": FONT_B}


def get_font(key: str) -> StrokeFont:
    try:
        return FONTS[key.upper()]
    except KeyError as exc:
        raise ValueError(f"Неизвестный шрифт: {key}") from exc


def glyph_catalog(font: StrokeFont | None = None) -> list[tuple[str, Glyph]]:
    """Упорядоченный список глифов для окна предпросмотра шрифта."""
    if font is None:
        font = FONT_A
    groups = [
        "АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ",
        "абвгдеёжзийклмнопрстуфхцчшщъыьэюя",
        "ABCDEFGHIJKLMNOPQRSTUVWXYZ",
        "abcdefghijklmnopqrstuvwxyz",
        "0123456789",
        ".,:;!?-–—()[]{}/\\\"'«»=+*%#№$<>|~^°±×÷⌀",
    ]
    out: list[tuple[str, Glyph]] = []
    for group in groups:
        for ch in group:
            g = font.glyph(ch)
            if g is not None:
                out.append((ch, g))
    return out
